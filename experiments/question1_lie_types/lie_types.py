"""Track D outside type A: does the face poset of a regular semisimple Hessenberg variety
determine its Betti numbers, for the other Lie types?

Setting.  Phi a root system with Weyl group W, I a lower order ideal of the poset of
positive roots.  Hess(I) in G/B is smooth of dimension |I|, its fixed points are the
w in W, the tangent weights at w are w(-I), and (De Mari-Procesi-Shayman)

    P(q) = sum_{w in W} q^#{alpha in I : w(alpha) < 0}.

Face poset.  The T-invariant curves at w join w to w s_alpha, alpha in I.  A face through w
is the connected component of w in the fixed set of a subtorus; its tangent weights at w
form w(F) for a flat F of the linear matroid of I, and its fixed points are the coset
w W_F, W_F the group generated by the reflections in F.  So

    S(Hess(I)) = { (F, w W_F) : F a flat of M(I), w in W },   ordered by inclusion,

of rank rk F, with nu(F, wW_F) = |W_F| fixed points below.  For type A this is the
cluster-permutohedron of the Hessenberg graph.  W acts on the poset by left
multiplication, transitively on the minimal elements, so the poset above any minimal
element is the lattice of flats L(I) with the function nu.

What is computed.  For every ideal I (with all simple roots, i.e. Hess(I) connected, and
without that restriction) of every listed type:
  * the Poincare polynomial;
  * the nu-labelled lattice of flats (L(I), nu) up to isomorphism (nauty), which is
    determined by the face poset;
and then: do two ideals -- of the same or of different types -- with isomorphic
(L, nu) have equal Poincare polynomials?  If (L, nu) already separates all Poincare
polynomials, the answer to Question 1 is yes on this class.

Run with the engine's interpreter:  ../../engine/.venv/bin/python lie_types.py [types...]
"""
from collections import defaultdict
from fractions import Fraction as Fr
from itertools import combinations
import json
import sys
import time

from mtengine.backends import nauty
from mtengine.domain import matroids as mt


def simple_roots(t, n):
    e = lambda i: tuple(Fr(int(k == i)) for k in range(n))
    sub = lambda a, b: tuple(x - y for x, y in zip(a, b))
    add = lambda a, b: tuple(x + y for x, y in zip(a, b))
    if t == "A":
        m = n + 1
        E = lambda i: tuple(Fr(int(k == i)) for k in range(m))
        return [sub(E(i), E(i + 1)) for i in range(n)]
    if t == "B":
        return [sub(e(i), e(i + 1)) for i in range(n - 1)] + [e(n - 1)]
    if t == "C":
        return [sub(e(i), e(i + 1)) for i in range(n - 1)] + [tuple(2 * x for x in e(n - 1))]
    if t == "D":
        return [sub(e(i), e(i + 1)) for i in range(n - 1)] + [add(e(n - 2), e(n - 1))]
    if t == "G":
        return [(Fr(1), Fr(-1), Fr(0)), (Fr(-2), Fr(1), Fr(1))]
    if t == "F":
        h = Fr(1, 2)
        return [sub(e(1), e(2)), sub(e(2), e(3)), e(3), (h, -h, -h, -h)]
    raise ValueError(t)


def reflect(a, v):
    c = 2 * sum(x * y for x, y in zip(a, v)) / sum(x * x for x in a)
    return tuple(x - c * y for x, y in zip(v, a))


class RootSystem:
    def __init__(self, t, n):
        self.name = f"{t}{n}"
        S = simple_roots(t, n)
        self.rank = n
        roots = set(S)
        todo = list(S)
        while todo:
            v = todo.pop()
            for a in S:
                w = reflect(a, v)
                if w not in roots:
                    roots.add(w)
                    todo.append(w)
        # coordinates in the basis of simple roots
        def coords(v):
            ech = mt._Echelon()
            # solve sum c_i S_i = v
            d = len(v)
            A = [[S[j][i] for j in range(n)] + [v[i]] for i in range(d)]
            row, piv = 0, []
            for c in range(n):
                p = next((i for i in range(row, d) if A[i][c]), None)
                if p is None:
                    continue
                A[row], A[p] = A[p], A[row]
                A[row] = [x / A[row][c] for x in A[row]]
                for i in range(d):
                    if i != row and A[i][c]:
                        f = A[i][c]
                        A[i] = [x - f * y for x, y in zip(A[i], A[row])]
                piv.append(c)
                row += 1
            out = [Fr(0)] * n
            for i, c in enumerate(piv):
                out[c] = A[i][-1]
            return tuple(out)
        co = {v: coords(v) for v in roots}
        pos = sorted((v for v in roots if all(x >= 0 for x in co[v])), key=lambda v: (sum(co[v]), co[v]))
        self.pos = pos                                   # positive roots, by height
        self.co = [co[v] for v in pos]
        self.N = len(pos)
        allr = pos + [tuple(-x for x in v) for v in pos]
        index = {v: i for i, v in enumerate(allr)}
        self.simple_idx = [index[a] for a in S]
        # reflections as permutations of all roots
        refl = [tuple(index[reflect(a, v)] for v in allr) for a in pos]
        self.refl = refl
        # Weyl group as permutations of the roots: w[i] = index of w(root i)
        ident = tuple(range(2 * self.N))
        W = {ident: 0}
        order = [ident]
        todo = [ident]
        while todo:
            w = todo.pop()
            for a in self.simple_idx:
                s = refl[a]
                ws = tuple(w[s[i]] for i in range(2 * self.N))        # w o s
                if ws not in W:
                    W[ws] = len(order)
                    order.append(ws)
                    todo.append(ws)
        self.W = order
        self.Windex = W
        # right multiplication table: rmul[a][k] = index of W[k] o s_a
        self.rmul = [[W[tuple(w[s[i]] for i in range(2 * self.N))] for w in order] for s in refl]
        # root poset: a <= b iff b - a is a nonnegative combination of simple roots
        self.leq = [[all(y - x >= 0 for x, y in zip(self.co[a], self.co[b])) for b in range(self.N)]
                    for a in range(self.N)]

    def ideals(self):
        """Lower order ideals of the positive roots, as sorted tuples of indices."""
        N = self.N
        below = [frozenset(a for a in range(N) if self.leq[a][b]) for b in range(N)]
        out = set()
        def rec(k, cur):
            if k == N:
                out.add(tuple(sorted(cur)))
                return
            rec(k + 1, cur)                              # exclude root k (heights increase with k)
            if below[k] - {k} <= cur:
                rec(k + 1, cur | {k})
        rec(0, frozenset())
        return sorted(out, key=lambda I: (len(I), I))

    def poincare(self, I):
        N = self.N
        c = defaultdict(int)
        for w in self.W:
            c[sum(1 for a in I if w[a] >= N)] += 1
        return tuple(c[i] for i in range(len(I) + 1))


def labelled_lattice(R, I):
    """(L(I), nu): flats of the matroid of the roots in I, each with nu = |W_F|; returned as a
    canonical form of the Hasse diagram coloured by (rank, nu), and a summary."""
    V = [R.pos[a] for a in I]
    if not V:
        return ("empty",), {"flats_by_rank": [1], "nu": {}}
    levels = mt.flats_by_rank(V)
    flats = [F for level in levels for F in level]
    rk = {F: k for k, level in enumerate(levels) for F in level}
    nW = len(R.W)
    nu = {}
    for F in flats:                                      # |W_F| = size of the component of the identity
        gens = [R.rmul[I[j]] for j in F]
        seen = {0}
        todo = [0]
        while todo:
            k = todo.pop()
            for g in gens:
                m = g[k]
                if m not in seen:
                    seen.add(m)
                    todo.append(m)
        nu[F] = len(seen)
    idx = {F: i for i, F in enumerate(flats)}
    edges = []
    for k in range(len(levels) - 1):
        for F in levels[k]:
            for G in levels[k + 1]:
                if F < G:
                    edges.append((idx[F], idx[G]))
    colours = defaultdict(list)
    for F in flats:
        colours[(rk[F], nu[F])].append(idx[F])
    keys = sorted(colours)
    form = nauty.canonical_form(len(flats), edges, [colours[k] for k in keys])
    summary = {"flats_by_rank": [len(l) for l in levels],
               "nu": {f"{k}": len(v) for k, v in sorted(colours.items())}}
    return (tuple(keys), json.dumps(form, sort_keys=True)), summary


def main(types):
    records = []
    for t, n in types:
        t0 = time.time()
        R = RootSystem(t, n)
        ideals = R.ideals()
        simple = set(range(n))                           # the first n positive roots are the simple ones
        for I in ideals:
            key, summary = labelled_lattice(R, I)
            records.append({"type": R.name, "ideal": I, "connected": simple <= set(I),
                            "poincare": R.poincare(I), "key": key, "summary": summary,
                            "W": len(R.W)})
        print(f"{R.name}: |W| = {len(R.W)}, {R.N} positive roots, {len(ideals)} ideals "
              f"({sum(1 for r in records if r['type'] == R.name and r['connected'])} connected), "
              f"{time.time() - t0:.1f}s", flush=True)
    for label, recs in (("connected ideals", [r for r in records if r["connected"]]), ("all ideals", records)):
        groups = defaultdict(list)
        for r in recs:
            groups[(r["W"], r["key"])].append(r)
        bad = {k: v for k, v in groups.items() if len({r["poincare"] for r in v}) > 1}
        cross = sum(1 for v in groups.values() if len({r["type"] for r in v}) > 1)
        betti_classes = len({(r["poincare"]) for r in recs})
        print(f"\n{label}: {len(recs)} ideals, {len(groups)} classes of (|W|, L, nu), "
              f"{betti_classes} Poincare polynomials")
        print(f"    classes containing ideals of different types: {cross}")
        print(f"    classes with more than one Poincare polynomial: {len(bad)}")
        for k, v in list(bad.items())[:10]:
            for r in v:
                print("       ", r["type"], r["ideal"], r["poincare"], r["summary"])
            print()
    return records


if __name__ == "__main__":
    default = [("A", 2), ("A", 3), ("B", 2), ("G", 2), ("B", 3), ("C", 3)]
    args = sys.argv[1:]
    types = [(a[0], int(a[1:])) for a in args] if args else default
    main(types)
